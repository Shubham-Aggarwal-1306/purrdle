import type { FastifyInstance } from 'fastify';
import { z } from 'zod';

import { JudgeUnavailableError } from '../judge/types.ts';
import type { JudgeService } from '../judge/service.ts';
import type { RequestAttestor } from '../security/attestation.ts';
import type { RateLimiter, RateLimitRule } from '../security/rate-limit.ts';

const MAX_TEXT = 64;

export const JudgeBodySchema = z
  .object({
    word: z.string().trim().min(1).max(MAX_TEXT),
    acceptedVariants: z.array(z.string().trim().min(1).max(MAX_TEXT)).max(20).default([]),
    guess: z.string().trim().min(1).max(MAX_TEXT),
  })
  .strict();

/** Random per-install ID generated by the app; used only as a rate-limit key. */
const InstallationIdSchema = z.string().regex(/^[A-Za-z0-9-]{8,64}$/);

export interface JudgeRouteOptions {
  service: JudgeService;
  limiter: RateLimiter;
  attestor: RequestAttestor;
  deviceRule: RateLimitRule;
  ipRule: RateLimitRule;
}

export function judgeRoutes(app: FastifyInstance, opts: JudgeRouteOptions): void {
  app.post('/judge', async (request, reply) => {
    if (!(await opts.attestor.verify(request))) {
      return reply.code(401).send({ error: 'unauthorized' });
    }

    const installationId = InstallationIdSchema.safeParse(request.headers['x-installation-id']);
    if (!installationId.success) {
      return reply.code(400).send({ error: 'missing_installation_id' });
    }

    const body = JudgeBodySchema.safeParse(request.body);
    if (!body.success) return reply.code(400).send({ error: 'invalid_body' });

    try {
      const limit = await opts.limiter.check([
        { rule: opts.ipRule, subject: request.ip },
        { rule: opts.deviceRule, subject: installationId.data },
      ]);
      if (!limit.allowed) {
        return await reply
          .code(429)
          .header('retry-after', String(limit.retryAfterSeconds))
          .send({ error: 'rate_limited' });
      }
      const outcome = await opts.service.decide(body.data);
      return await reply.send(outcome);
    } catch (err) {
      request.log.warn({ err }, 'judge unavailable');
      if (!(err instanceof JudgeUnavailableError)) request.log.error({ err }, 'judge route error');
      return reply.code(503).send({ error: 'unavailable' });
    }
  });
}
